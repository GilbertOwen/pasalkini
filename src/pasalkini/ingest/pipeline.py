"""Run the Phase 1 pipeline for each instrument: extract → parse → data/processed/<id>.json."""

from pathlib import Path

from pasalkini.ingest.download import load_lock, raw_path
from pasalkini.ingest.extract import extract_lines
from pasalkini.ingest.models import ParsedDocument
from pasalkini.ingest.parse import (
    build_articles,
    cut_scope,
    join_lines,
    parse_amar,
    parse_penjelasan,
    segment,
    split_parts,
)
from pasalkini.ingest.review import closing_dates
from pasalkini.paths import PROCESSED_DIR, ROOT
from pasalkini.sources import Instrument, Kind, load_manifest

REPORT_PATH = ROOT / "docs" / "parse-report.md"


def processed_path(instrument_id: str) -> Path:
    return PROCESSED_DIR / f"{instrument_id}.json"


def parse_instrument(instrument: Instrument) -> ParsedDocument:
    lock = load_lock()
    hints = instrument.parse
    warnings: list[str] = []
    where = instrument.id

    files = {"main": lock[instrument.id]["sha256"]}
    lines = extract_lines(raw_path(instrument.id))

    doc = ParsedDocument(
        instrument_id=instrument.id,
        text_layer=instrument.text_layer or "unknown",
        files=files,
        scope=f"{hints.scope_start} … {hints.scope_end}" if hints.scope_start else None,
    )

    if instrument.kind is Kind.PUTUSAN_MK:
        doc.amar, doc.closing = parse_amar(lines, where, warnings)
        doc.warnings = warnings
        return doc

    body, closing, penjelasan = split_parts(lines)
    doc.closing = join_lines([ln.text for ln in closing[:40]])
    if hints.scope_start and hints.scope_end:
        body = cut_scope(body, hints.scope_start, hints.scope_end, where, warnings)

    roman = hints.own_numbering == "roman"
    blocks = segment(body, roman, first_any=bool(hints.scope_start), where=where, warnings=warnings)
    doc.articles = build_articles(instrument.id, blocks, where, warnings)
    if not doc.articles:
        warnings.append(f"{where}: no articles found")

    if hints.penjelasan:
        if instrument.penjelasan_pdf_url:
            files["penjelasan"] = lock[f"{instrument.id}.penjelasan"]["sha256"]
            penjelasan = extract_lines(raw_path(instrument.id, "penjelasan"))
        if penjelasan:
            umum, per_article = parse_penjelasan(penjelasan, roman, f"{where} penjelasan", warnings)
            doc.penjelasan_umum = umum
            for article in doc.articles:
                article.penjelasan = per_article.get(article.number)
        else:
            warnings.append(f"{where}: no penjelasan found")

    doc.warnings = warnings
    return doc


def summarize(doc: ParsedDocument) -> dict:
    articles = doc.articles
    ayat = sum(len(a.ayat) for a in articles)
    points = [p for a in articles for p in a.points]
    embedded = sum(len(p.articles) for p in points)
    with_pj = sum(1 for a in articles if a.penjelasan)
    numbers = [a.number for a in articles]
    return {
        "id": doc.instrument_id,
        "layer": doc.text_layer,
        "articles": len(articles),
        "range": f"{numbers[0]}–{numbers[-1]}" if numbers else "",
        "ayat": ayat,
        "points": len(points),
        "inferred": sum(p.number_inferred for p in points),
        "embedded": embedded,
        "penjelasan": f"{with_pj}/{len(articles)}" if articles else "",
        "amar": len(doc.amar),
        "warnings": len(doc.warnings),
    }


def write_report(docs: list[ParsedDocument]) -> None:
    rows = [summarize(d) for d in docs]
    columns = [
        ("id", "Instrument"),
        ("layer", "Text"),
        ("articles", "Articles"),
        ("range", "Pasal"),
        ("ayat", "Ayat"),
        ("points", "Amendment points"),
        ("inferred", "Inferred numbers"),
        ("embedded", "Quoted articles"),
        ("penjelasan", "With penjelasan"),
        ("amar", "Amar points"),
        ("warnings", "Warnings"),
    ]
    out = [
        "# Parse report",
        "",
        "Generated by `uv run pasalkini parse`. Counts come from `data/processed/*.json`.",
        "",
        "| " + " | ".join(title for _, title in columns) + " |",
        "|" + "---|" * len(columns),
    ]
    for row in rows:
        out.append("| " + " | ".join(str(row[key]) for key, _ in columns) + " |")
    out += [
        "",
        "## Dates found in the documents",
        "",
        "Read by the parser from each document's closing. Check them against the PDF before",
        "copying them into `sources/manifest.yaml` and setting `dates_verified: true`.",
        "",
        "| Instrument | Found |",
        "|---|---|",
    ]
    for doc in docs:
        out.append(f"| {doc.instrument_id} | {'; '.join(closing_dates(doc)) or '—'} |")
    out += ["", "## Warnings", ""]
    for doc in docs:
        if doc.warnings:
            out.append(f"### {doc.instrument_id}")
            out.append("")
            out += [f"- {w}" for w in doc.warnings[:50]]
            if len(doc.warnings) > 50:
                out.append(f"- … and {len(doc.warnings) - 50} more")
            out.append("")
    # LF on every platform: the report is in git, and a rebuild should not show it as changed.
    REPORT_PATH.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


def run(only: list[str] | None = None) -> list[ParsedDocument]:
    manifest = load_manifest()
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    docs = []
    for instrument in manifest.instruments:
        if instrument.status != "active" or (only and instrument.id not in only):
            continue
        doc = parse_instrument(instrument)
        processed_path(instrument.id).write_text(doc.model_dump_json(indent=1), encoding="utf-8")
        row = summarize(doc)
        print(
            f"  {row['id']:<24} articles={row['articles']:<4} ayat={row['ayat']:<5} "
            f"points={row['points']:<4} amar={row['amar']:<3} warnings={row['warnings']}",
            flush=True,
        )
        docs.append(doc)
    if not only:
        write_report(docs)
    return docs
